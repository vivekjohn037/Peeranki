-- ============================================================================
-- Peeranki Multiplayer Schema & RPC Migration
-- Compatible with Supabase PostgreSQL (PostgREST + Realtime)
-- ============================================================================

-- 1. Ensure extensions
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. Create public.game_states table
CREATE TABLE IF NOT EXISTS public.game_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code VARCHAR(6) NOT NULL UNIQUE,
    players JSONB NOT NULL DEFAULT '[]'::jsonb,
    max_players INTEGER NOT NULL DEFAULT 4 CHECK (max_players >= 2 AND max_players <= 10),
    is_public BOOLEAN NOT NULL DEFAULT false,
    host_session_id TEXT NOT NULL CHECK (length(trim(host_session_id)) > 0),
    current_shooter INTEGER DEFAULT NULL,
    countdown INTEGER NOT NULL DEFAULT 0,
    counting_start_timestamp TIMESTAMPTZ DEFAULT NULL,
    game_status TEXT NOT NULL DEFAULT 'waiting' CHECK (game_status IN ('waiting', 'playing', 'shooting', 'counting', 'duel', 'finished')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. Indexes for fast lookup & matchmaking
CREATE UNIQUE INDEX IF NOT EXISTS idx_game_states_room_code ON public.game_states (room_code);
CREATE INDEX IF NOT EXISTS idx_game_states_matchmaking ON public.game_states (is_public, game_status, max_players) WHERE is_public = true AND game_status = 'waiting';
CREATE INDEX IF NOT EXISTS idx_game_states_updated_at ON public.game_states (updated_at DESC);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.game_states ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if any to allow idempotent re-running
DROP POLICY IF EXISTS "Allow public read access" ON public.game_states;
DROP POLICY IF EXISTS "Allow public insert" ON public.game_states;
DROP POLICY IF EXISTS "Allow public update" ON public.game_states;

-- Read policy: Anyone with the public/anon key can read game states
CREATE POLICY "Allow public read access"
ON public.game_states
FOR SELECT
TO anon, authenticated
USING (true);

-- Insert policy: Anyone can create new game states
CREATE POLICY "Allow public insert"
ON public.game_states
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Update policy: Anyone can update game states (restricted by room code in app/RPC)
CREATE POLICY "Allow public update"
ON public.game_states
FOR UPDATE
TO anon, authenticated
USING (true)
WITH CHECK (true);

-- Grant table privileges to anon and authenticated roles
GRANT SELECT, INSERT, UPDATE, DELETE ON public.game_states TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

