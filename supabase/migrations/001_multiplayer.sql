-- ----------------------------------------------------------------------------
-- RPC 1: join_private_room
-- Joins an existing room or reconnects a returning session
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.join_private_room(
    p_room_code TEXT,
    p_player_name TEXT,
    p_session_id TEXT
)
RETURNS public.game_states
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_code TEXT := upper(trim(coalesce(p_room_code, '')));
    v_name TEXT := trim(coalesce(p_player_name, ''));
    v_session TEXT := trim(coalesce(p_session_id, ''));
    v_room public.game_states%ROWTYPE;
    v_players JSONB;
    v_player_idx INTEGER := -1;
    v_connected_count INTEGER := 0;
    v_used_ids INTEGER[] := ARRAY[]::INTEGER[];
    v_next_id INTEGER := 1;
    v_i INTEGER;
    v_elem JSONB;
    v_now TEXT := to_jsonb(now()::timestamptz)#>>'{}';
BEGIN
    IF length(v_code) != 6 THEN
        RAISE EXCEPTION 'Room does not exist' USING ERRCODE = 'P0001';
    END IF;

    IF length(v_session) = 0 THEN
        RAISE EXCEPTION 'Invalid session identifier' USING ERRCODE = 'P0002';
    END IF;

    IF length(v_name) = 0 THEN
        v_name := 'Player';
    ELSE
        v_name := substring(v_name from 1 for 16);
    END IF;

    -- Lock row for concurrency
    SELECT * INTO v_room
    FROM public.game_states
    WHERE room_code = v_code
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Room does not exist' USING ERRCODE = 'P0001';
    END IF;

    v_players := coalesce(v_room.players, '[]'::jsonb);

    -- Check if session already exists in player list
    FOR v_i IN 0 .. (jsonb_array_length(v_players) - 1) LOOP
        v_elem := v_players->v_i;
        IF (v_elem->>'session_id') = v_session THEN
            v_player_idx := v_i;
        END IF;
        IF (v_elem->>'connected')::boolean = true THEN
            v_connected_count := v_connected_count + 1;
        END IF;
        v_used_ids := array_append(v_used_ids, (v_elem->>'id')::integer);
    END LOOP;

    -- If player already in room, reconnect them
    IF v_player_idx >= 0 THEN
        v_players := jsonb_set(
            v_players,
            ARRAY[v_player_idx::text, 'connected'],
            'true'::jsonb
        );
        v_players := jsonb_set(
            v_players,
            ARRAY[v_player_idx::text, 'name'],
            to_jsonb(v_name)
        );
        v_players := jsonb_set(
            v_players,
            ARRAY[v_player_idx::text, 'last_seen'],
            to_jsonb(v_now)
        );
    ELSE
        -- Match in progress cannot accept new players
        IF v_room.game_status != 'waiting' THEN
            RAISE EXCEPTION 'Game already in progress' USING ERRCODE = 'P0004';
        END IF;

        -- Capacity check
        IF v_connected_count >= v_room.max_players THEN
            RAISE EXCEPTION 'Room is full' USING ERRCODE = 'P0005';
        END IF;

        -- Find smallest unused player id
        WHILE v_next_id = ANY(v_used_ids) AND v_next_id <= v_room.max_players LOOP
            v_next_id := v_next_id + 1;
        END LOOP;

        v_players := v_players || jsonb_build_array(
            jsonb_build_object(
                'id', v_next_id,
                'name', v_name,
                'stage', 0,
                'alive', true,
                'session_id', v_session,
                'connected', true,
                'last_seen', v_now,
                'weapons', jsonb_build_array('gun'),
                'all_weapons_collected', false,
                'elimination_points', 0,
                'shield_disabled_round', -1
            )
        );
    END IF;

    UPDATE public.game_states
    SET players = v_players,
        updated_at = now()
    WHERE room_code = v_code
    RETURNING * INTO v_room;

    RETURN v_room;
END;
$$;

-- ----------------------------------------------------------------------------
-- RPC 2: find_or_create_public_room
-- Finds an available public waiting room or creates a new one
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.find_or_create_public_room(
    p_max_players INTEGER,
    p_player_name TEXT,
    p_session_id TEXT
)
RETURNS public.game_states
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_max INTEGER := greatest(3, least(10, coalesce(p_max_players, 4)));
    v_name TEXT := trim(coalesce(p_player_name, ''));
    v_session TEXT := trim(coalesce(p_session_id, ''));
    v_room public.game_states%ROWTYPE;
    v_code TEXT;
    v_chars TEXT := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    v_i INTEGER;
    v_now TEXT := to_jsonb(now()::timestamptz)#>>'{}';
    v_attempts INTEGER := 0;
BEGIN
    IF length(v_name) = 0 THEN
        v_name := 'Player';
    ELSE
        v_name := substring(v_name from 1 for 16);
    END IF;

    IF length(v_session) = 0 THEN
        RAISE EXCEPTION 'Invalid session identifier' USING ERRCODE = 'P0002';
    END IF;

    -- 1. Try to find an existing waiting public room with space
    FOR v_room IN
        SELECT *
        FROM public.game_states
        WHERE is_public = true
          AND game_status = 'waiting'
          AND max_players = v_max
        ORDER BY created_at ASC
        FOR UPDATE SKIP LOCKED
    LOOP
        -- Check if room has space
        IF (SELECT count(*) FROM jsonb_array_elements(v_room.players) elem WHERE (elem->>'connected')::boolean = true) < v_max THEN
            -- Join this room
            RETURN public.join_private_room(v_room.room_code, v_name, v_session);
        END IF;
    END LOOP;

    -- 2. No waiting room found; generate a new room code and create one
    LOOP
        v_attempts := v_attempts + 1;
        v_code := '';
        FOR v_i IN 1..6 LOOP
            v_code := v_code || substr(v_chars, floor(random() * length(v_chars) + 1)::integer, 1);
        END LOOP;

        BEGIN
            INSERT INTO public.game_states (
                room_code,
                players,
                max_players,
                is_public,
                host_session_id,
                current_shooter,
                countdown,
                game_status,
                created_at,
                updated_at
            ) VALUES (
                v_code,
                jsonb_build_array(
                    jsonb_build_object(
                        'id', 1,
                        'name', v_name,
                        'stage', 0,
                        'alive', true,
                        'session_id', v_session,
                        'connected', true,
                        'last_seen', v_now,
                        'weapons', jsonb_build_array('gun'),
                        'all_weapons_collected', false,
                        'elimination_points', 0,
                        'shield_disabled_round', -1
                    )
                ),
                v_max,
                true,
                v_session,
                NULL,
                0,
                'waiting',
                now(),
                now()
            )
            RETURNING * INTO v_room;

            RETURN v_room;
        EXCEPTION WHEN unique_violation THEN
            IF v_attempts > 10 THEN
                RAISE EXCEPTION 'Could not generate unique room code' USING ERRCODE = 'P0006';
            END IF;
        END;
    END LOOP;
END;
$$;

-- ----------------------------------------------------------------------------
-- RPC 3: touch_player
-- Heartbeat update to maintain connected status
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.touch_player(
    p_room_code TEXT,
    p_session_id TEXT
)
RETURNS public.game_states
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_code TEXT := upper(trim(coalesce(p_room_code, '')));
    v_session TEXT := trim(coalesce(p_session_id, ''));
    v_room public.game_states%ROWTYPE;
    v_players JSONB;
    v_i INTEGER;
    v_elem JSONB;
    v_found BOOLEAN := false;
    v_now TEXT := to_jsonb(now()::timestamptz)#>>'{}';
BEGIN
    SELECT * INTO v_room
    FROM public.game_states
    WHERE room_code = v_code
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    v_players := coalesce(v_room.players, '[]'::jsonb);

    FOR v_i IN 0 .. (jsonb_array_length(v_players) - 1) LOOP
        v_elem := v_players->v_i;
        IF (v_elem->>'session_id') = v_session THEN
            v_players := jsonb_set(
                v_players,
                ARRAY[v_i::text, 'last_seen'],
                to_jsonb(v_now)
            );
            v_players := jsonb_set(
                v_players,
                ARRAY[v_i::text, 'connected'],
                'true'::jsonb
            );
            v_found := true;
            EXIT;
        END IF;
    END LOOP;

    IF v_found THEN
        UPDATE public.game_states
        SET players = v_players,
            updated_at = now()
        WHERE room_code = v_code
        RETURNING * INTO v_room;
    END IF;

    RETURN v_room;
END;
$$;

-- ----------------------------------------------------------------------------
-- RPC 4: cleanup_stale_players
-- Disconnects players who have not sent a heartbeat within stale threshold
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.cleanup_stale_players(
    p_room_code TEXT,
    p_stale_seconds INTEGER DEFAULT 30
)
RETURNS public.game_states
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_code TEXT := upper(trim(coalesce(p_room_code, '')));
    v_threshold INTEGER := greatest(10, least(300, coalesce(p_stale_seconds, 30)));
    v_room public.game_states%ROWTYPE;
    v_players JSONB;
    v_i INTEGER;
    v_elem JSONB;
    v_last_seen TIMESTAMPTZ;
    v_cutoff TIMESTAMPTZ := now() - (v_threshold || ' seconds')::interval;
    v_changed BOOLEAN := false;
BEGIN
    SELECT * INTO v_room
    FROM public.game_states
    WHERE room_code = v_code
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    v_players := coalesce(v_room.players, '[]'::jsonb);

    FOR v_i IN 0 .. (jsonb_array_length(v_players) - 1) LOOP
        v_elem := v_players->v_i;
        IF (v_elem->>'connected')::boolean = true THEN
            v_last_seen := (v_elem->>'last_seen')::timestamptz;
            IF v_last_seen IS NOT NULL AND v_last_seen < v_cutoff THEN
                v_players := jsonb_set(
                    v_players,
                    ARRAY[v_i::text, 'connected'],
                    'false'::jsonb
                );
                v_changed := true;
            END IF;
        END IF;
    END LOOP;

    IF v_changed THEN
        UPDATE public.game_states
        SET players = v_players,
            updated_at = now()
        WHERE room_code = v_code
        RETURNING * INTO v_room;
    END IF;

    RETURN v_room;
END;
$$;

-- ----------------------------------------------------------------------------
-- RPC 5: leave_room
-- Sets player to disconnected & dead when leaving intentionally
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.leave_room(
    p_room_code TEXT,
    p_session_id TEXT
)
RETURNS public.game_states
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_code TEXT := upper(trim(coalesce(p_room_code, '')));
    v_session TEXT := trim(coalesce(p_session_id, ''));
    v_room public.game_states%ROWTYPE;
    v_players JSONB;
    v_i INTEGER;
    v_elem JSONB;
    v_changed BOOLEAN := false;
    v_now TEXT := to_jsonb(now()::timestamptz)#>>'{}';
BEGIN
    SELECT * INTO v_room
    FROM public.game_states
    WHERE room_code = v_code
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    v_players := coalesce(v_room.players, '[]'::jsonb);

    FOR v_i IN 0 .. (jsonb_array_length(v_players) - 1) LOOP
        v_elem := v_players->v_i;
        IF (v_elem->>'session_id') = v_session THEN
            v_players := jsonb_set(v_players, ARRAY[v_i::text, 'connected'], 'false'::jsonb);
            v_players := jsonb_set(v_players, ARRAY[v_i::text, 'alive'], 'false'::jsonb);
            v_players := jsonb_set(v_players, ARRAY[v_i::text, 'last_seen'], to_jsonb(v_now));
            v_changed := true;
            EXIT;
        END IF;
    END LOOP;

    IF v_changed THEN
        UPDATE public.game_states
        SET players = v_players,
            updated_at = now()
        WHERE room_code = v_code
        RETURNING * INTO v_room;
    END IF;

    RETURN v_room;
END;
$$;

-- Grant EXECUTE privileges to anon and authenticated on all RPCs
GRANT EXECUTE ON FUNCTION public.join_private_room TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.find_or_create_public_room TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.touch_player TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.cleanup_stale_players TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.leave_room TO anon, authenticated;

-- ============================================================================
-- 6. Supabase Realtime Configuration
-- ============================================================================
-- Ensure full row payloads are delivered on postgres changes
ALTER TABLE public.game_states REPLICA IDENTITY FULL;

-- Add table to realtime publication (wrapped in DO block for idempotency)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = 'game_states'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.game_states;
    END IF;
EXCEPTION WHEN OTHERS THEN
    -- Fallback for environments where publication is managed separately
    NULL;
END;
$$;
